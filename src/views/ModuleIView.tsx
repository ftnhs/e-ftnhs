import React, { useState, useEffect, useMemo, useCallback } from"react";
import { useAuth } from"../context/AuthContext";
import type {
  LeaveApplication,
  LeaveClassRelief,
  AcademicTerm,
  Profile,
  SchoolSettings,
  TimeSlotOverride,
} from"../types";
import { fetchLeaveApplications } from"../services/leaveReliefService";
import { fetchTimetableData } from"../services/timetableService";
import { PageHeader } from"../components/common/PageHeader";
import { StatCard } from"../components/common/StatCard";
import { NewLeaveApplicationModal } from"../components/leave/NewLeaveApplicationModal";
import { LeaveDetailsModal } from"../components/leave/LeaveDetailsModal";
import { ConformeResponseModal } from"../components/leave/ConformeResponseModal";
import { PrintableLeaveLetter } from"../components/leave/PrintableLeaveLetter";
import {
  Send,
  Plus,
  Search,
  Filter,
  CheckCircle,
  Clock,
  XCircle,
  UserCheck,
  Calendar,
  AlertCircle,
  ChevronRight,
} from"lucide-react";

export const ModuleIView: React.FC = () => {
  const { profile } = useAuth();
  const [activeTab, setActiveTab] = useState<"all" |"my_leaves" |"conforme_requests">("all");
  const [applications, setApplications] = useState<LeaveApplication[]>([]);
  const [activeTerm, setActiveTerm] = useState<AcademicTerm | null>(null);
  const [teachers, setTeachers] = useState<Profile[]>([]);
  const [schoolSettings, setSchoolSettings] = useState<SchoolSettings | null>(null);
  const [timeSlotOverrides, setTimeSlotOverrides] = useState<TimeSlotOverride[]>([]);
  const [isLoading, setIsLoading] = useState<boolean>(true);

  // Search & Filter state
  const [searchQuery, setSearchQuery] = useState<string>("");
  const [statusFilter, setStatusFilter] = useState<string>("All");

  // Modal dialog states
  const [isNewModalOpen, setIsNewModalOpen] = useState<boolean>(false);
  const [selectedApp, setSelectedApp] = useState<LeaveApplication | null>(null);
  const [autoGeneratedLetterApp, setAutoGeneratedLetterApp] = useState<LeaveApplication | null>(null);

  // Conforme Action modal state
  const [conformeTarget, setConformeTarget] = useState<{
    relief: LeaveClassRelief;
    app: LeaveApplication;
  } | null>(null);

  const loadData = useCallback(async () => {
    setIsLoading(true);
    try {
      const [apps, timetable] = await Promise.all([
        fetchLeaveApplications(profile?.id, profile?.role),
        fetchTimetableData(),
      ]);
      setApplications(apps);
      setActiveTerm(timetable.activeTerm);
      setTeachers(timetable.teachers);
      setSchoolSettings(timetable.schoolSettings);
      setTimeSlotOverrides(timetable.timeSlotOverrides);
    } catch (err) {
      console.error("Error loading leave applications:", err);
    } finally {
      setIsLoading(false);
    }
  }, [profile?.id, profile?.role]);

  useEffect(() => {
    loadData();
  }, [loadData]);

  // Pending relief requests where current user is designated reliever
  const pendingReliefsForMe = useMemo(() => {
    if (!profile) return [];
    const list: Array<{ relief: LeaveClassRelief; app: LeaveApplication }> = [];
    applications.forEach((app) => {
      app.reliefs?.forEach((r) => {
        if (r.reliever_teacher_id === profile.id && r.conforme_status ==="Pending") {
          list.push({ relief: r, app });
        }
      });
    });
    return list;
  }, [applications, profile]);

  // Filtered applications based on active tab and filters
  const filteredApplications = useMemo(() => {
    return applications.filter((app) => {
      // Tab Filtering
      if (activeTab ==="my_leaves" && app.teacher_id !== profile?.id) {
        return false;
      }
      if (activeTab ==="conforme_requests") {
        const isReliever = app.reliefs?.some(
          (r) => r.reliever_teacher_id === profile?.id
        );
        if (!isReliever) return false;
      }

      // Status Filtering
      if (statusFilter !=="All" && app.status !== statusFilter) {
        return false;
      }

      // Search Query
      if (searchQuery.trim()) {
        const q = searchQuery.toLowerCase();
        const teacherName = app.teacher?.full_name?.toLowerCase() ||"";
        const leaveType = app.leave_type.toLowerCase();
        const reason = app.reason.toLowerCase();
        if (!teacherName.includes(q) && !leaveType.includes(q) && !reason.includes(q)) {
          return false;
        }
      }

      return true;
    });
  }, [applications, activeTab, statusFilter, searchQuery, profile?.id]);

  // Executive Metric Counts
  const metrics = useMemo(() => {
    let pendingRelief = 0;
    let pendingApproval = 0;
    let approved = 0;
    applications.forEach((app) => {
      if (app.status ==="Pending_Relief") pendingRelief++;
      if (app.status ==="Pending_Approval") pendingApproval++;
      if (app.status ==="Approved") approved++;
    });
    return {
      total: applications.length,
      pendingRelief,
      pendingApproval,
      approved,
    };
  }, [applications]);

  return (
    <div className="p-4 sm:p-6 lg:p-8 max-w-7xl mx-auto space-y-6">
      <PageHeader
        title="Leave & Relief"
        primaryAction={{
          label:"File Leave",
          icon: <Plus className="w-4 h-4" />,
          onClick: () => setIsNewModalOpen(true),
        }}
      />

      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <StatCard
          label="Total Applications"
          value={metrics.total}
          icon={<Send className="w-4 h-4" />}
        />
        <StatCard
          label="Awaiting Relievers"
          value={metrics.pendingRelief}
          icon={<UserCheck className="w-4 h-4" />}
        />
        <StatCard
          label="Awaiting Principal"
          value={metrics.pendingApproval}
          icon={<Clock className="w-4 h-4" />}
          accent={metrics.pendingApproval > 0 ?"crimson" :"default"}
        />
        <StatCard
          label="Approved Leaves"
          value={metrics.approved}
          icon={<CheckCircle className="w-4 h-4" />}
          accent="green"
        />
      </div>

      {/* 3. Action Alert for Relievers (If any pending requests for current user) */}
      {pendingReliefsForMe.length > 0 && (
        <div className="p-4 rounded-xl bg-[#FBECEF] border border-[#F3B8C2] text-[#9E1B32] flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
          <div className="flex items-center gap-3">
            <AlertCircle className="w-5 h-5 text-[#9E1B32] shrink-0" />
            <div>
              <div className="text-xs font-bold">
                You have {pendingReliefsForMe.length} Pending Class Relief{" "}
                {pendingReliefsForMe.length === 1 ? "Request" : "Requests"}
              </div>
              <p className="text-[11px] text-[#7F1528]">
                Colleagues have designated you to cover classes during their official leave. Please review and confirm your conforme.
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={() => setActiveTab("conforme_requests")}
            className="px-3.5 py-2 rounded-lg bg-[#9E1B32] hover:bg-[#7F1528] text-white text-xs font-semibold transition-colors shrink-0 cursor-pointer whitespace-nowrap"
          >
            Review Relief Requests
          </button>
        </div>
      )}

      {/* 4. Controls: Tabs, Search & Status Filter */}
      <div className="bg-white rounded-2xl border border-[#E3DDD1] p-4 shadow-2xs space-y-4 transition-colors">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 border-b border-[#E3DDD1] pb-3">
          {/* Navigation Tabs */}
          <div className="flex items-center gap-1.5 p-1 rounded-xl bg-[#FAF8F5] border border-[#E3DDD1] text-xs max-w-full overflow-x-auto no-scrollbar">
            <button
              type="button"
              onClick={() => setActiveTab("all")}
              className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer whitespace-nowrap shrink-0 ${
                activeTab === "all"
                  ? "bg-[#E6EFEA] text-[#0F3D2E]"
                  : "text-[#5C6660] hover:text-[#1C2420]"
              }`}
            >
              All Applications ({applications.length})
            </button>
            <button
              type="button"
              onClick={() => setActiveTab("my_leaves")}
              className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer whitespace-nowrap shrink-0 ${
                activeTab === "my_leaves"
                  ? "bg-[#E6EFEA] text-[#0F3D2E]"
                  : "text-[#5C6660] hover:text-[#1C2420]"
              }`}
            >
              My Applications
            </button>
            <button
              type="button"
              onClick={() => setActiveTab("conforme_requests")}
              className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer whitespace-nowrap shrink-0 relative ${
                activeTab === "conforme_requests"
                  ? "bg-[#E6EFEA] text-[#0F3D2E]"
                  : "text-[#5C6660] hover:text-[#1C2420]"
              }`}
            >
              Relief Requests
              {pendingReliefsForMe.length > 0 && (
                <span className="ml-1.5 px-1.5 py-0.2 rounded-full bg-[#9E1B32] text-white text-[10px] font-bold">
                  {pendingReliefsForMe.length}
                </span>
              )}
            </button>
          </div>

          {/* Search & Filter Controls */}
          <div className="flex items-center gap-2 w-full sm:w-auto">
            <div className="relative flex-1 sm:w-64">
              <Search className="w-3.5 h-3.5 text-sand-500 absolute left-3 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                placeholder="Search teacher or leave type..."
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="w-full pl-8 pr-3 py-1.5 rounded-xl border border-sand-300 bg-sand-50 text-xs text-cyprus-900 placeholder:text-sand-500 focus:outline-hidden focus:ring-2 focus:ring-cyprus-700"
              />
            </div>

            <div className="flex items-center gap-1.5">
              <Filter className="w-3.5 h-3.5 text-sand-500 shrink-0" />
              <select
                value={statusFilter}
                onChange={(e) => setStatusFilter(e.target.value)}
                className="px-2.5 py-1.5 rounded-xl border border-sand-300 bg-sand-50 text-xs text-cyprus-900 font-semibold focus:outline-hidden focus:ring-2 focus:ring-cyprus-700"
              >
                <option value="All">All Statuses</option>
                <option value="Pending_Relief">Pending Relief</option>
                <option value="Pending_Approval">Pending Approval</option>
                <option value="Approved">Approved</option>
                <option value="Disapproved">Disapproved</option>
              </select>
            </div>
          </div>
        </div>

        {/* 5. Applications Table / Card Grid */}
        {isLoading ? (
          <div className="p-12 text-center text-xs text-sand-600">
            Loading leave applications and conforme status...
          </div>
        ) : filteredApplications.length === 0 ? (
          <div className="p-12 text-center space-y-2">
            <div className="w-12 h-12 rounded-full bg-sand-100 text-sand-600 flex items-center justify-center mx-auto">
              <Send className="w-6 h-6" />
            </div>
            <div className="text-sm font-bold text-cyprus-900">
              No leave applications found
            </div>
            <p className="text-xs text-sand-600">
              {searchQuery ?"Try refining your search terms." :"No applications match the current filter criteria."}
            </p>
          </div>
        ) : (
          <div className="border border-sand-200 rounded-xl overflow-hidden shadow-xs">
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs">
                <thead className="bg-sand-100 text-cyprus-900 text-[11px] font-bold border-b border-sand-200">
                  <tr>
                    <th className="py-3 px-4">Applicant</th>
                    <th className="py-3 px-4">Type of Leave</th>
                    <th className="py-3 px-4">Inclusive Dates</th>
                    <th className="py-3 px-4">Relief Status</th>
                    <th className="py-3 px-4">Workflow Status</th>
                    <th className="py-3 px-4 text-right">Actions</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-sand-200">
                  {filteredApplications.map((app) => {
                    const totalReliefs = app.reliefs?.length || 0;
                    const acceptedReliefs =
                      app.reliefs?.filter((r) => r.conforme_status ==="Accepted").length || 0;
                    const declinedReliefs =
                      app.reliefs?.filter((r) => r.conforme_status ==="Declined").length || 0;

                    // Check if current user has a pending action in this app
                    const myPendingRelief = app.reliefs?.find(
                      (r) =>
                        r.reliever_teacher_id === profile?.id &&
                        r.conforme_status ==="Pending"
                    );

                    return (
                      <tr
                        key={app.id}
                        className="hover:bg-sand-50/70 transition-colors"
                      >
                        <td className="py-3 px-4">
                          <div className="font-bold text-cyprus-900">
                            {app.teacher?.full_name ||"Faculty Member"}
                          </div>
                          <div className="text-[11px] text-sand-600">
                            {app.teacher?.department ||"Junior High School"}
                          </div>
                        </td>

                        <td className="py-3 px-4 font-semibold text-cyprus-900">
                          {app.leave_type}
                        </td>

                        <td className="py-3 px-4 whitespace-nowrap">
                          <div className="flex items-center gap-1 font-semibold text-cyprus-900">
                            <Calendar className="w-3.5 h-3.5 text-crimson-600" />
                            {app.start_date} to {app.end_date}
                          </div>
                          <div className="text-[11px] text-sand-600">
                            {app.total_days} {app.total_days === 1 ?"day" :"days"} (working)
                          </div>
                        </td>

                        <td className="py-3 px-4 whitespace-nowrap">
                          {totalReliefs === 0 ? (
                            <span className="text-[11px] text-sand-500 italic">No classes affected</span>
                          ) : declinedReliefs > 0 ? (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-crimson-100 text-crimson-800 text-[11px] font-bold border border-crimson-200">
                              <XCircle className="w-3 h-3" />
                              {declinedReliefs} Declined
                            </span>
                          ) : acceptedReliefs === totalReliefs ? (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-[#E6EFEA] text-[#0F3D2E] text-[11px] font-semibold border border-[#B8CEC5]">
                              <CheckCircle className="w-3 h-3" />
                              {acceptedReliefs}/{totalReliefs} Accepted
                            </span>
                          ) : (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-[#FAF8F5] text-[#5C6660] text-[11px] font-semibold border border-[#E3DDD1]">
                              <Clock className="w-3 h-3" />
                              {acceptedReliefs}/{totalReliefs} Conforme
                            </span>
                          )}
                        </td>

                        <td className="py-3 px-4 whitespace-nowrap">
                          <span
                            className={`inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-semibold ${
                              app.status === "Approved"
                                ? "bg-[#E6EFEA] text-[#0F3D2E] border border-[#B8CEC5]"
                                : app.status === "Disapproved"
                                ? "bg-[#FBECEF] text-[#9E1B32] border border-[#F3B8C2]"
                                : app.status === "Pending_Approval"
                                ? "bg-[#E6EFEA]/70 text-[#0F3D2E] border border-[#B8CEC5]"
                                : "bg-[#FAF8F5] text-[#5C6660] border border-[#E3DDD1]"
                            }`}
                          >
                            {app.status === "Approved" && <CheckCircle className="w-3 h-3" />}
                            {app.status === "Disapproved" && <XCircle className="w-3 h-3" />}
                            {app.status === "Pending_Approval" && <Clock className="w-3 h-3" />}
                            {app.status === "Pending_Relief" && <UserCheck className="w-3 h-3" />}
                            {app.status.replace("_", " ")}
                          </span>
                        </td>

                        <td className="py-3 px-4 text-right whitespace-nowrap">
                          <div className="flex items-center justify-end gap-2">
                            {myPendingRelief && (
                              <button
                                type="button"
                                onClick={() =>
                                  setConformeTarget({
                                    relief: myPendingRelief,
                                    app,
                                  })
                                }
                                className="px-2.5 py-1 rounded-lg bg-[#0F3D2E] hover:bg-[#0A2E22] text-white text-xs font-semibold transition-colors cursor-pointer"
                              >
                                Sign Conforme
                              </button>
                            )}

                            <button
                              type="button"
                              onClick={() => setSelectedApp(app)}
                              className="px-2.5 py-1 rounded-lg border border-sand-300 hover:bg-sand-100 text-cyprus-900 text-xs font-semibold transition-colors flex items-center gap-1 cursor-pointer"
                            >
                              <span>Inspect</span>
                              <ChevronRight className="w-3.5 h-3.5 text-sand-500" />
                            </button>
                          </div>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </div>
        )}
      </div>

      {/* 6. Modals */}
      {profile && (
        <NewLeaveApplicationModal
          isOpen={isNewModalOpen}
          onClose={() => setIsNewModalOpen(false)}
          activeTerm={activeTerm}
          currentUser={profile}
          teachers={teachers}
          onApplicationCreated={(newApp) => {
            loadData();
            setAutoGeneratedLetterApp(newApp);
          }}
        />
      )}

      {selectedApp && profile && (
        <LeaveDetailsModal
          isOpen={!!selectedApp}
          onClose={() => setSelectedApp(null)}
          leaveApp={selectedApp}
          currentUser={profile}
          teachers={teachers}
          schoolSettings={schoolSettings}
          timeSlotOverrides={timeSlotOverrides}
          onUpdate={() => loadData()}
        />
      )}

      {autoGeneratedLetterApp && (
        <PrintableLeaveLetter
          isOpen={!!autoGeneratedLetterApp}
          onClose={() => setAutoGeneratedLetterApp(null)}
          leaveApp={autoGeneratedLetterApp}
          schoolSettings={schoolSettings}
          timeSlotOverrides={timeSlotOverrides}
        />
      )}

      {conformeTarget && (
        <ConformeResponseModal
          isOpen={!!conformeTarget}
          onClose={() => setConformeTarget(null)}
          relief={conformeTarget.relief}
          leaveApp={conformeTarget.app}
          onActionComplete={() => loadData()}
        />
      )}
    </div>
  );
};
